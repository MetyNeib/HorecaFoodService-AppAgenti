import { test, expect } from '@playwright/test';
import { login, reset, snapshot } from './helpers.mjs';

test('cambio cliente reversibile, svuotamento, quantità, rimozione e cancellazione bozza', async ({ page }) => {
  page.on('pageerror', error => { throw error; });
  await login(page); await reset(page);
  const orderId = 'BOZ-26-00021';
  const currentOrder = async () => (await snapshot(page)).state.data.orders.find(order => order.id === orderId);
  await page.goto(`/orders/${orderId}/products`);
  await page.getByRole('link', { name: 'Cambia cliente' }).click();
  await expect(page.getByRole('heading', { name: 'Seleziona il cliente', exact: true })).toBeVisible();
  await page.getByRole('searchbox').fill('061002');
  await expect(page.getByRole('button', { name: /Seleziona/ })).toHaveCount(1);
  await page.getByRole('button', { name: /Seleziona/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Il carrello verrà svuotato');
  await page.keyboard.press('Escape');
  expect((await currentOrder()).customerId).toBe('CLI-061001');
  expect((await currentOrder()).lines).toHaveLength(2);
  await page.getByRole('button', { name: /Seleziona/ }).click();
  await page.getByRole('button', { name: 'Svuota e cambia cliente' }).click();
  await expect(page.getByRole('heading', { name: 'Cerca e aggiungi prodotti' })).toBeVisible();
  const customer = (await snapshot(page)).state.data.customers.find(item => item.id === 'CLI-061002');
  const order = await currentOrder();
  expect(order.customerId).toBe(customer.id);
  expect(order.lines).toHaveLength(0);
  expect(order.paymentId).toBe(customer.defaultPaymentId);
  expect(order.totals.netCents).toBe(0);
  await expect(page.getByRole('button', { name: /Vai al riepilogo/ })).toBeDisabled();
  await page.getByRole('searchbox').fill('0107417');
  await expect(page.locator('.product-card')).toHaveCount(1);
  await page.getByTestId('product-0107417').getByRole('button', { name: '+ Aggiungi', exact: true }).click();
  const line = page.getByTestId('line-0107417');
  await expect(line).toBeVisible();
  await line.getByRole('button', { name: 'Aumenta quantità' }).click();
  await expect.poll(async () => (await currentOrder()).lines[0].quantity).toBe(2);
  await page.reload();
  await expect.poll(async () => Number(await line.getByRole('spinbutton', { name: 'Quantità' }).inputValue())).toBe(2);
  await line.getByRole('button', { name: 'Rimuovi', exact: true }).click();
  await expect(line).toHaveCount(0);
  expect((await currentOrder()).lines).toHaveLength(0);
  await page.getByRole('button', { name: 'Salva bozza', exact: true }).click();
  const row = page.locator('article').filter({ hasText: orderId });
  await row.getByRole('button', { name: 'Elimina bozza' }).click();
  await page.keyboard.press('Escape');
  expect(await currentOrder()).toBeDefined();
  await row.getByRole('button', { name: 'Elimina bozza' }).click();
  await page.getByRole('button', { name: 'Elimina definitivamente' }).click();
  await expect(row).toHaveCount(0);
  await page.reload();
  expect(await currentOrder()).toBeUndefined();
});
