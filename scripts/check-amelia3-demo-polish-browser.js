async (page) => {
 const results = [];
 for (const [name, viewport] of [['desktop', {width:1440,height:900}], ['phone', {width:390,height:844}]]) {
  const context = await page.context().browser().newContext({viewport,locale:'it-IT'});
  const p = await context.newPage();
  const check = (value, label) => { if (!value) throw Error(name + ': ' + label); };
  const go = path => p.evaluate(path => window.HFS.navigate(path), path);
  const wait = fn => p.waitForFunction(fn, null, {timeout:30000});
  let phase = 'login';
  const errors = [];
  p.on('pageerror', () => errors.push('javascript_error'));
  await context.route('**/*', async route => {
   const u = new URL(route.request().url());
   if (['http:','https:'].includes(u.protocol) && !['127.0.0.1','localhost'].includes(u.hostname)) { errors.push('external_request'); await route.abort(); } else await route.continue();
  });
  try {
   await p.goto('http://127.0.0.1:3002/users/sign_in');
   await p.getByLabel('Email',{exact:true}).fill('amelia-admin-qa@example.invalid');
   await p.getByLabel('Password',{exact:true}).fill('TestHfsLocale2026!');
   await p.getByRole('button',{name:'Accedi',exact:true}).click();
   await wait(() => !!window.HFS?.client?.record);
   await p.evaluate(() => window.HFS.ready);
   await wait(() => window.HFS.offlinePrepared && navigator.serviceWorker.controller);
   check(await p.evaluate(() => window.HFS.client.snapshot.state.data.tenant.code === 'amelia3-browser-qa'), 'synthetic tenant guard');
   await go('/amelia3');
   await context.setOffline(true); await go('/amelia3');
   check(await p.locator('.amelia-connection').isVisible(), 'offline bar');
   check((await p.locator('.amelia-connection').innerText()).includes('Offline'), 'offline text');
   await p.getByRole('button',{name:'Apri menu',exact:true}).click();
   check((await p.locator('#amelia-menu .amelia_connection_text_js').innerText()).includes('Offline'), 'offline menu');
   await p.keyboard.press('Escape');
   await p.screenshot({path:'output/playwright/polish-'+name+'-offline.png'});
   await context.setOffline(false); await p.evaluate(() => window.HFS.reconnect());
   await wait(() => !window.HFS.offlineView && !window.HFS.client.syncing);
   check(await p.locator('.home-orders').count() === 1, 'home restored without reload');
   await go('/amelia3/customers?category=blocked');
   check(await p.locator('[data-customer-code="C002"]').count() === 1, 'blocked tab');
   await go('/amelia3/customers?category=dormant');
   check(await p.locator('[data-customer-code="C003"]').count() === 1, 'dormant tab');
   await p.screenshot({path:'output/playwright/polish-'+name+'-customers.png'});
   await go('/amelia3/customers?pick=1');
   check(await p.locator('[data-customer-code="C002"]').count() === 0, 'picker excludes blocked');
   check(await p.locator('[aria-label="Categorie clienti"]').count() === 0, 'picker no tabs');
   check((await p.locator('[data-customer-code="C003"]').innerText()).includes('Fermo'), 'picker dormant badge');
   await go('/amelia3/customers?pick=1&q=C001');
   await p.getByRole('button',{name:'Seleziona →',exact:true}).click();
   await p.getByRole('heading',{name:'Cerca e aggiungi prodotti',exact:true}).waitFor();
   const orderId = new URL(p.url()).searchParams.get('order_id');
   const product = p.locator('[data-product-code="KG005"]');
   await product.getByRole('button',{name:'+ Aggiungi',exact:true}).click();
   await p.locator('[data-line-id]').waitFor();
   const saved = () => p.evaluate(id => window.HFS.client.snapshot.state.data.orders.find(o=>o.id===id),orderId);
   phase = 'unit-online';
   const before = await saved();
   const line = p.locator('[data-line-id]').first();
   await line.getByRole('combobox').selectOption('KG');
   check(Number(await line.getByRole('spinbutton').inputValue()) === 5, 'verified equivalent COLL to KG');
   await line.getByRole('button',{name:'Salva riga',exact:true}).click();
   await wait(() => !window.HFS.client.record.outbox.length && !window.HFS.client.syncing);
   await p.waitForFunction(id => window.HFS.client.snapshot.state.data.orders.find(o=>o.id===id).lines[0].unit==='KG', orderId, {timeout:15000});
   await wait(() => document.querySelector('[data-line-id] small')?.textContent.endsWith('UM KG'));
   check((await saved()).lines.length === 1, 'unit persisted same line');
   check((await saved()).netCents === before.netCents, 'same amount after conversion');
   phase = 'unit-offline';
   await context.setOffline(true);
   await go('/amelia3/catalog?order_id='+orderId);
   await line.getByRole('combobox').selectOption('COLL');
   check(Number(await line.getByRole('spinbutton').inputValue()) === 1, 'offline equivalence');
   await line.getByRole('button',{name:'Salva riga',exact:true}).click();
   await p.waitForFunction(id => window.HFS.client.snapshot.state.data.orders.find(o=>o.id===id).lines[0].unit==='COLL',orderId);
   await wait(() => document.querySelector('[data-line-id] small')?.textContent.endsWith('UM COLL'));
   await line.getByRole('combobox').selectOption('KG');
   phase = 'fractional-offline';
   await line.getByRole('spinbutton').fill('0.25');
   await line.getByRole('button',{name:'Salva riga',exact:true}).click();
   await p.waitForFunction(id => window.HFS.client.snapshot.state.data.orders.find(o=>o.id===id).lines[0].unit==='KG',orderId);
   await wait(() => document.querySelector('[data-line-id] small')?.textContent.endsWith('UM KG'));
   await line.getByRole('combobox').selectOption('COLL');
   check(await line.getByRole('spinbutton').inputValue() === '', 'non-divisible equivalence requires new quantity');
   phase = 'reconnect-pending';
   await context.setOffline(false); await p.evaluate(() => window.HFS.reconnect());
   await wait(() => !window.HFS.client.record.outbox.length && !window.HFS.client.syncing);
   check(await line.getByRole('spinbutton').inputValue() === '', 'reconnect preserves unsaved choice');
   phase = 'manual-quantity';
   await line.getByRole('spinbutton').fill('1');
   await line.getByRole('button',{name:'Salva riga',exact:true}).click();
   await wait(() => !window.HFS.client.record.outbox.length && !window.HFS.client.syncing);
   await wait(() => document.querySelector('[data-line-id] small')?.textContent.endsWith('UM COLL'));
   await go('/amelia3/catalog?order_id='+orderId);
   check((await saved()).lines[0].unit === 'COLL', 'manual unit quantity persisted');
   check(!(await p.locator('main').innerText()).includes('preferita'), 'no repeated preferred label');
   check(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), 'cart no overflow');
   await p.screenshot({path:'output/playwright/polish-'+name+'-cart.png'});
   await go('/amelia3/orders?status=HISTORY');
   await p.getByRole('link',{name:'Dettaglio storico',exact:true}).first().click();
   await p.locator('.amelia-history-quantity').first().waitFor({state:'visible'});
   check(await p.locator('.amelia-history-quantity').count() > 0, 'one quantity per historical line');
   check(await p.locator('.amelia-quantities').count() === 0, 'raw multiple quantities removed');
   await go('/amelia3/alerts');
   check(await p.locator('.amelia-alert__summary').count() > 0, 'prominent alert explanation');
   check(!(await p.locator('main').innerText()).includes('mediano'), 'plain language');
   check(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), 'alert no overflow');
   await p.screenshot({path:'output/playwright/polish-'+name+'-alerts.png'});
   check(errors.length===0,'browser errors');
   results.push({profile:name,status:'PASS',homeReconnect:true,customerTabs:true,picker:true,cartUnitsOnlineOffline:true,history:true,alerts:true});
  } catch (error) { return {profile:name,status:'FAIL',phase,error:error.message,notice:await p.locator('.snackbar').textContent(),state:await p.evaluate(() => ({online:navigator.onLine,reachable:window.HFS?.client?.reachable,syncing:window.HFS?.client?.syncing,lastError:window.HFS?.client?.lastError,pending:window.HFS?.client?.record?.outbox.length,units:window.HFS?.client?.snapshot?.state.data.orders[0]?.lines.map(l=>l.unit),conflict:window.HFS?.client?.record?.conflict?.message}))}; } finally { await context.close(); }
 }
 return results;
}
